"""Write the README's data tables from the experiment JSON, between committed markers.

Hand-typed table cells are the largest hole in a receipts mechanism. An anchor phrase guards a
figure quoted in a sentence; a table of thirty numbers is thirty figures nobody anchored, and
the first one to go stale goes stale silently.

So the tables are generated. Each block in the README is delimited by a marker comment, this
tool rewrites the rows between them from `docs/experiments/*.json`, and CI regenerates and
fails if the committed README differs. The numbers in those rows are then exactly the numbers
the experiments produced, and the same values are published in `docs/metrics.json` under
`table_values` so the backward check in check_numbers.py recognises them.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
EXPERIMENTS = ROOT / "docs" / "experiments"

SWEEP_ROWS = (1, 5, 20, 50)


def _block(name: str, body: str, source: str) -> str:
    return (
        f"<!-- table:{name} generated by tools/render_tables.py from {source} -->\n"
        f"{body}\n"
        f"<!-- /table:{name} -->"
    )


def sweep_table() -> tuple[str, list[Any]]:
    payload = json.loads((EXPERIMENTS / "exp02_k_sweep.json").read_text())
    values: list[Any] = []
    lines = [
        "| k | recall@k as scored | strict recall | answerable |",
        "| --- | --- | --- | --- |",
    ]
    for point in payload["points"]:
        if point["k"] not in SWEEP_ROWS:
            continue
        values.extend(
            [point["k"], point["recall_generous_pct"], point["recall_strict_pct"],
             point["answerable_pct"]]
        )
        lines.append(
            f"| {point['k']} | {point['recall_generous_pct']}% | "
            f"{point['recall_strict_pct']}% | {point['answerable_pct']}% |"
        )
    return _block("sweep", "\n".join(lines), "exp02_k_sweep.json"), values


def chunker_table() -> tuple[str, list[Any]]:
    payload = json.loads((EXPERIMENTS / "exp03_chunker_tradeoff.json").read_text())
    values: list[Any] = []
    lines = [
        "| chunker | chunks | index | answerable | strict recall | rank and embedding misses |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for name in sorted(payload["chunkers"]):
        row = payload["chunkers"][name]
        misses = row["rank_misses"] + row["embedding_misses"]
        values.extend(
            [row["chunks"], row["index_multiple"], row["answerable_pct"],
             row["recall_strict_pct"], misses]
        )
        lines.append(
            f"| `{name}` | {row['chunks']} | {row['index_multiple']}x | "
            f"{row['answerable_pct']}% | {row['recall_strict_pct']}% | {misses} |"
        )
    return _block("chunkers", "\n".join(lines), "exp03_chunker_tradeoff.json"), values


def table_values() -> list[Any]:
    """Every number the generated tables contain, for the backward check to recognise."""
    _, sweep = sweep_table()
    _, chunkers = chunker_table()
    return sweep + chunkers


def main() -> int:
    text = README.read_text(encoding="utf-8")
    replaced = 0
    for name, builder in (("sweep", sweep_table), ("chunkers", chunker_table)):
        block, _ = builder()
        pattern = re.compile(
            rf"<!-- table:{name}.*?-->.*?<!-- /table:{name} -->", re.DOTALL
        )
        if not pattern.search(text):
            print(f"no marker block for {name!r} in README.md")
            return 1
        text = pattern.sub(lambda _match, block=block: block, text)
        replaced += 1
    README.write_text(text, encoding="utf-8")
    print(f"rewrote {replaced} generated table block(s) in README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
